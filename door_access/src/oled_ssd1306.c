#define TAG        "oled"
#define OLED_PORT  I2C_NUM_0
#define OLED_SDA   21
#define OLED_SCL   22
#define OLED_ADDR  0x3C          /* some modules use 0x3D */
#define OLED_W     128
#define OLED_PAGES 8

/* Control byte that starts every I2C message to the SSD1306:
 *   0x00 = the bytes after me are COMMANDS
 *   0x40 = the bytes after me are DISPLAY DATA
 *   0x80 = one command follows, then another control byte (Co=1)   */
#define CTRL_CMD_STREAM 0x00
#define CTRL_DATA       0x40
#define CTRL_CMD_ONE    0x80

static uint8_t fb[OLED_PAGES * OLED_W];   /* page p = text row p */

