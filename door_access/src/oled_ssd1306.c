static esp_err_t oled_cmd(uint8_t c)
{
    i2c_cmd_handle_t h = i2c_cmd_link_create();
    i2c_master_start(h);
    i2c_master_write_byte(h, (OLED_ADDR << 1) | I2C_MASTER_WRITE, true);
    i2c_master_write_byte(h, CTRL_CMD_STREAM, true);
    i2c_master_write_byte(h, c, true);
    i2c_master_stop(h);
    esp_err_t e = i2c_master_cmd_begin(OLED_PORT, h, pdMS_TO_TICKS(100));
    i2c_cmd_link_delete(h);
    return e;
}

esp_err_t oled_init(void)
{
    i2c_config_t cfg = {
        .mode = I2C_MODE_MASTER,
        .sda_io_num = OLED_SDA,
        .scl_io_num = OLED_SCL,
        .sda_pullup_en = GPIO_PULLUP_ENABLE,
        .scl_pullup_en = GPIO_PULLUP_ENABLE,
        .master.clk_speed = 400000,
    };
    ESP_ERROR_CHECK(i2c_param_config(OLED_PORT, &cfg));
    ESP_ERROR_CHECK(i2c_driver_install(OLED_PORT, I2C_MODE_MASTER, 0, 0, 0));

    static const uint8_t init_seq[] = {
        0xAE,             /* display OFF while configuring            */
        0xD5, 0x80,       /* clock divide / oscillator                */
        0xA8, 0x3F,       /* multiplex = 64 rows                      */
        0xD3, 0x00,       /* display offset = 0                       */
        0x40,             /* start line = 0                           */
        0x8D, 0x14,       /* charge pump ON (needed with 3.3 V)       */
        0x20, 0x02,       /* PAGE addressing mode                     */
        0xA1,             /* segment remap  (flip X if text mirrored) */
        0xC8,             /* COM scan reversed (flip Y if upside down)*/
        0xDA, 0x12,       /* COM pins config for 128x64               */
        0x81, 0xCF,       /* contrast                                 */
        0xD9, 0xF1,       /* pre-charge                               */
        0xDB, 0x40,       /* VCOMH level                              */
        0xA4,             /* show RAM content                         */
        0xA6,             /* normal (not inverted)                    */
        0xAF,             /* display ON                               */
    };
    for (size_t i = 0; i < sizeof init_seq; i++) {
        esp_err_t e = oled_cmd(init_seq[i]);
        if (e != ESP_OK) {
            ESP_LOGE(TAG, "no ACK from OLED at 0x%02X (check SDA/SCL/power/address)", OLED_ADDR);
            return e;
        }
    }
    oled_clear();
    return oled_flush();
}

void oled_clear(void)              { memset(fb, 0, sizeof fb); }
void oled_clear_row(uint8_t row)   { if (row < OLED_ROWS) memset(&fb[row * OLED_W], 0, OLED_W); }

void oled_text(uint8_t col, uint8_t row, const char *s)
{
    if (row >= OLED_ROWS || s == NULL) return;
    int x = col * 6;
    for (; *s && x + 6 <= OLED_W; s++, x += 6) {
        int c = toupper((unsigned char)*s);
        if (c < 0x20 || c > 0x5F) c = '?';
        memcpy(&fb[row * OLED_W + x], font5x7[c - 0x20], 5);
        fb[row * OLED_W + x + 5] = 0x00;      /* 1 blank column between chars */
    }
}

/* One I2C transaction per page: "set page + column" commands and then 128 data bytes. */
esp_err_t oled_flush(void)
{
    for (uint8_t p = 0; p < OLED_PAGES; p++) {
        i2c_cmd_handle_t h = i2c_cmd_link_create();
        i2c_master_start(h);
        i2c_master_write_byte(h, (OLED_ADDR << 1) | I2C_MASTER_WRITE, true);
        i2c_master_write_byte(h, CTRL_CMD_ONE, true); i2c_master_write_byte(h, 0xB0 | p, true); /* page      */
        i2c_master_write_byte(h, CTRL_CMD_ONE, true); i2c_master_write_byte(h, 0x00, true);     /* col low   */
        i2c_master_write_byte(h, CTRL_CMD_ONE, true); i2c_master_write_byte(h, 0x10, true);     /* col high  */
        i2c_master_write_byte(h, CTRL_DATA, true);
        i2c_master_write(h, &fb[p * OLED_W], OLED_W, true);
        i2c_master_stop(h);
        esp_err_t e = i2c_master_cmd_begin(OLED_PORT, h, pdMS_TO_TICKS(100));
        i2c_cmd_link_delete(h);
        if (e != ESP_OK) return e;
    }
    return ESP_OK;
}
